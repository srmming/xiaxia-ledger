# 图层：(颜料, 路径, 描边宽度；0 = 填充)
def S(p): return ('soft', p, 0)
def D(p): return ('solid', p, 0)
def H(p): return ('hi', p, 0)
def X(p): return ('cut', p, 0)
def Ss(p, w=1.8): return ('soft', p, w)
def Ds(p, w=1.8): return ('solid', p, w)
def Hs(p, w=1.2): return ('hi', p, w)
def Xs(p, w=1.6): return ('cut', p, w)

def shine(x, y, l=2.6, w=1.3):
    """左上角一小道白色反光：可爱感主要靠它。"""
    return Hs(arc(x + l, y + l, l, 180, 250), w)

